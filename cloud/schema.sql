-- A função usa os privilégios de quem a chama, inclusive as políticas RLS.
CREATE OR REPLACE FUNCTION public.salvar_produto(p_produto_id bigint, p_dados jsonb, p_variacoes jsonb)
 RETURNS bigint
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare v_id bigint; v_variacao jsonb;
begin
  if not exists(select 1 from public.loja_admins where user_id = (select auth.uid())) then
    raise exception 'Acesso restrito.' using errcode = '42501';
  end if;
  if jsonb_typeof(p_variacoes) <> 'array' or jsonb_array_length(p_variacoes) > 12 then
    raise exception 'Envie no máximo 12 variações por vez.' using errcode = '22023';
  end if;
  if p_produto_id is null then
    if jsonb_array_length(p_variacoes) = 0 then
      raise exception 'Informe uma cor e uma foto.' using errcode = '22023';
    end if;
    insert into public.produtos (nome, descricao, categoria, preco_avista, preco_parcelado, preco_total_parcelado, qtd_parcelas,
      em_promocao, preco_promocional, em_destaque, origem_local_id, ativo)
    values (trim(p_dados->>'nome'), coalesce(p_dados->>'descricao',''), trim(p_dados->>'categoria'),
      (p_dados->>'preco_avista')::numeric, (p_dados->>'preco_parcelado')::numeric,
      nullif(p_dados->>'preco_total_parcelado','')::numeric,
      (p_dados->>'qtd_parcelas')::integer, coalesce((p_dados->>'em_promocao')::boolean,false),
      (p_dados->>'preco_promocional')::numeric, coalesce((p_dados->>'em_destaque')::boolean,false),
      (p_dados->>'origem_local_id')::bigint, coalesce((p_dados->>'ativo')::boolean,true))
    returning id into v_id;
  else
    update public.produtos set nome=trim(p_dados->>'nome'), descricao=coalesce(p_dados->>'descricao',''),
      categoria=trim(p_dados->>'categoria'), preco_avista=(p_dados->>'preco_avista')::numeric,
      preco_parcelado=(p_dados->>'preco_parcelado')::numeric,
      preco_total_parcelado=case when p_dados ? 'preco_total_parcelado' then nullif(p_dados->>'preco_total_parcelado','')::numeric else preco_total_parcelado end, qtd_parcelas=(p_dados->>'qtd_parcelas')::integer,
      em_promocao=coalesce((p_dados->>'em_promocao')::boolean,false),
      preco_promocional=(p_dados->>'preco_promocional')::numeric,
      em_destaque=coalesce((p_dados->>'em_destaque')::boolean,false)
    where id=p_produto_id returning id into v_id;
    if v_id is null then raise exception 'Produto não encontrado.' using errcode='P0002'; end if;
  end if;
  for v_variacao in select value from jsonb_array_elements(p_variacoes) loop
    insert into public.variacoes(produto_id, cor, imagem_path)
      values(v_id, trim(v_variacao->>'cor'), v_variacao->>'imagem_path');
  end loop;
  return v_id;
end;
$function$;
revoke execute on function public.salvar_produto(bigint,jsonb,jsonb) from public, anon;
grant execute on function public.salvar_produto(bigint,jsonb,jsonb) to authenticated;

create function public.metricas_catalogo()
returns jsonb language plpgsql stable security invoker set search_path = '' as $$
declare resultado jsonb;
begin
  if not exists(select 1 from public.loja_admins where user_id = (select auth.uid())) then
    raise exception 'Acesso restrito.' using errcode = '42501';
  end if;
  select jsonb_build_object(
    'visitas',(select count(*) from public.eventos where tipo='visita_catalogo'),
    'cliques_whatsapp',(select count(*) from public.eventos where tipo='clique_whatsapp'),
    'top_produtos',coalesce((select jsonb_agg(to_jsonb(r)) from (
      select p.nome,count(*) as cliques from public.eventos e join public.produtos p on p.id=e.produto_id
      where e.tipo='clique_whatsapp' group by p.id,p.nome order by count(*) desc limit 5
    ) r),'[]'::jsonb)) into resultado;
  return resultado;
end;
$$;
revoke execute on function public.metricas_catalogo() from public, anon;
grant execute on function public.metricas_catalogo() to authenticated;
