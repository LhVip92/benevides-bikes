-- Estrutura de referência para projeto novo. Não executar sobre o banco existente.
-- Benevides Bikes: projeto dedicado, acesso público somente ao catálogo ativo.
create table public.loja_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  criado_em timestamptz not null default now()
);
alter table public.loja_admins enable row level security;
revoke all on public.loja_admins from anon, authenticated;
grant select on public.loja_admins to authenticated;
create policy "Administrador consulta seu vínculo" on public.loja_admins
  for select to authenticated using (user_id = (select auth.uid()));

create table public.produtos (
  id bigint generated by default as identity primary key,
  origem_local_id bigint unique,
  nome text not null check (char_length(trim(nome)) between 1 and 150),
  descricao text not null default '' check (char_length(descricao) <= 4000),
  categoria text not null check (char_length(trim(categoria)) between 1 and 80),
  preco_avista numeric(12,2) not null check (preco_avista between 0.01 and 1000000),
  preco_parcelado numeric(12,2) not null check (preco_parcelado between 0.01 and 1000000),
  preco_total_parcelado numeric(12,2) check (preco_total_parcelado between 0.01 and 1000000),
  qtd_parcelas integer not null default 10 check (qtd_parcelas between 1 and 36),
  em_promocao boolean not null default false,
  preco_promocional numeric(12,2),
  em_destaque boolean not null default false,
  ativo boolean not null default true,
  check (not em_promocao or (preco_promocional is not null and preco_promocional between 0.01 and preco_avista))
);
create table public.variacoes (
  id bigint generated by default as identity primary key,
  produto_id bigint not null references public.produtos(id) on delete cascade,
  cor text not null check (char_length(trim(cor)) between 1 and 80),
  imagem_path text not null unique check (imagem_path ~ '^produtos/[a-f0-9-]{36}\.webp$')
);
create index variacoes_produto_id_idx on public.variacoes(produto_id);
create table public.eventos (
  id bigint generated by default as identity primary key,
  tipo text not null check (tipo in ('visita_catalogo', 'clique_whatsapp')),
  produto_id bigint references public.produtos(id) on delete set null,
  data_hora timestamptz not null default now()
);
create index eventos_produto_id_idx on public.eventos(produto_id);
create index eventos_tipo_idx on public.eventos(tipo);

alter table public.produtos enable row level security;
alter table public.variacoes enable row level security;
alter table public.eventos enable row level security;
revoke all on public.produtos, public.variacoes, public.eventos from anon, authenticated;
grant select on public.produtos, public.variacoes to anon, authenticated;
grant insert, update, delete on public.produtos, public.variacoes to authenticated;
grant select on public.eventos to authenticated;
grant insert(tipo, produto_id) on public.eventos to anon, authenticated;
grant usage on sequence public.produtos_id_seq, public.variacoes_id_seq to authenticated;
grant usage on sequence public.eventos_id_seq to anon, authenticated;

create policy "Catálogo ativo" on public.produtos for select to anon, authenticated using (ativo);
create policy "Administra produtos" on public.produtos for all to authenticated
  using (exists(select 1 from public.loja_admins where user_id = (select auth.uid())))
  with check (exists(select 1 from public.loja_admins where user_id = (select auth.uid())));
create policy "Fotos do catálogo ativo" on public.variacoes for select to anon, authenticated
  using (exists(select 1 from public.produtos p where p.id = produto_id and p.ativo));
create policy "Administra variações" on public.variacoes for all to authenticated
  using (exists(select 1 from public.loja_admins where user_id = (select auth.uid())))
  with check (exists(select 1 from public.loja_admins where user_id = (select auth.uid())));
create policy "Registra métricas públicas" on public.eventos for insert to anon, authenticated
  with check (produto_id is null or exists(select 1 from public.produtos p where p.id = produto_id and p.ativo));
create policy "Admin consulta métricas" on public.eventos for select to authenticated
  using (exists(select 1 from public.loja_admins where user_id = (select auth.uid())));

